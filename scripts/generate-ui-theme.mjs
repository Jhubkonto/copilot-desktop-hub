import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sourcePath = resolve(repoRoot, 'design/nexy-8bit-theme.json')
const cssPath = resolve(repoRoot, 'src/renderer/styles/generated-theme.css')
const kotlinPath = resolve(
  repoRoot,
  'android/app/src/main/java/io/nexy/android/ui/theme/GeneratedNexyColors.kt',
)
const checkOnly = process.argv.includes('--check')

const tokens = JSON.parse(await readFile(sourcePath, 'utf8'))

function kebab(value) {
  return value.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()
}

function pascal(value) {
  return value.charAt(0).toUpperCase() + value.slice(1)
}

function rgbChannels(hex) {
  const value = hex.replace('#', '')
  return [0, 2, 4].map((offset) => Number.parseInt(value.slice(offset, offset + 2), 16)).join(' ')
}

function kotlinColor(hex) {
  return `Color(0xFF${hex.slice(1).toUpperCase()})`
}

function cssVariables(entries, prefix = '--nexy') {
  return Object.entries(entries).map(([key, value]) => `  ${prefix}-${kebab(key)}: ${rgbChannels(value)};`)
}

function buildCss() {
  const light = cssVariables(tokens.themes.light)
  const dark = cssVariables(tokens.themes.dark)
  const neutral = cssVariables(tokens.neutralRamp, '--nexy-neutral')
  const semantic = Object.entries(tokens.semantic).flatMap(([name, shades]) =>
    cssVariables(shades, `--nexy-${kebab(name)}`),
  )
  const projects = Object.entries(tokens.projects).flatMap(([name, shades]) =>
    cssVariables(shades, `--nexy-project-${kebab(name)}`),
  )
  const geometry = [
    ...Object.entries(tokens.geometry.desktop).map(([key, value]) =>
      `  --nexy-desktop-${kebab(key)}: ${value}px;`,
    ),
    ...Object.entries(tokens.geometry.android).map(([key, value]) =>
      `  --nexy-android-${kebab(key)}: ${value}px;`,
    ),
  ]

  return `/* Generated by scripts/generate-ui-theme.mjs. Do not edit directly. */\n:root {\n${[
    ...light,
    ...neutral,
    ...semantic,
    ...projects,
    ...geometry,
  ].join('\n')}\n}\n\n.dark {\n${dark.join('\n')}\n}\n`
}

function buildKotlin() {
  const themed = Object.entries(tokens.themes).flatMap(([themeName, values]) =>
    Object.entries(values).map(
      ([name, value]) => `    val ${pascal(themeName)}${pascal(name)} = ${kotlinColor(value)}`,
    ),
  )
  const neutral = Object.entries(tokens.neutralRamp).map(
    ([name, value]) => `    val Neutral${name} = ${kotlinColor(value)}`,
  )
  const semantic = Object.entries(tokens.semantic).flatMap(([name, shades]) =>
    Object.entries(shades).map(
      ([shade, value]) => `    val Semantic${pascal(name)}${pascal(shade)} = ${kotlinColor(value)}`,
    ),
  )
  const projects = Object.entries(tokens.projects).flatMap(([name, shades]) =>
    Object.entries(shades).map(
      ([shade, value]) => `    val Project${pascal(name)}${pascal(shade)} = ${kotlinColor(value)}`,
    ),
  )

  return `// Generated by scripts/generate-ui-theme.mjs. Do not edit directly.\npackage io.nexy.android.ui.theme\n\nimport androidx.compose.ui.graphics.Color\n\nobject GeneratedNexyColors {\n${[
    ...themed,
    ...neutral,
    ...semantic,
    ...projects,
  ].join('\n')}\n}\n`
}

async function emit(path, expected) {
  if (checkOnly) {
    let actual = ''
    try {
      actual = await readFile(path, 'utf8')
    } catch {
      // A missing generated file is stale by definition.
    }
    if (actual !== expected) {
      throw new Error(`${path.slice(repoRoot.length + 1)} is stale. Run npm run generate:ui-theme.`)
    }
    return
  }

  await mkdir(dirname(path), { recursive: true })
  await writeFile(path, expected, 'utf8')
}

await emit(cssPath, buildCss())
await emit(kotlinPath, buildKotlin())

if (checkOnly) {
  console.log('Generated UI theme files are up to date.')
} else {
  console.log('Generated desktop and Android UI theme files.')
}
